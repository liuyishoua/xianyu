"""Live tab retention regression; run only against an isolated DemoPlatform server."""
import os
from playwright.sync_api import sync_playwright, expect

base = os.environ.get('XIANYU_DEMO_URL', 'http://127.0.0.1:18770').rstrip('/')
checks = []
with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/google-chrome', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 1440, 'height': 900})
    assert context.request.get(base + '/api/meta').json()['demo'], 'Demo accounts only'
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda error: errors.append(str(error)))
    polls = {'dm': 0, 'comment': 0}
    def count_poll(request):
        for surface in polls:
            if request.url == base + '/api/monitoring/' + surface:
                polls[surface] += 1
    page.on('request', count_poll)
    page.on('dialog', lambda dialog: dialog.dismiss())
    def tab(name):
        page.locator(f'a.navlink[href="/{name}"]').click()
    page.goto(base + '/products')
    expect(page.locator('#product-search')).to_be_visible()
    page.evaluate("window.savedProduct=document.querySelector('#product-search');window.savedShell=document.querySelector('.shell')")
    page.locator('#product-search').fill('Kindle')
    expect(page.locator('#products-body')).to_contain_text('Kindle')
    tab('templates')
    expect(page.get_by_role('heading', name='话术库', exact=True)).to_be_visible()
    tab('products')
    expect(page.locator('#product-search')).to_have_value('Kindle')
    assert page.evaluate("savedProduct===document.querySelector('#product-search')&&savedShell===document.querySelector('.shell')")
    expect(page.locator('.page-loading')).to_have_count(0)
    page.locator('#product-search').fill('Marshall')
    expect(page.locator('#products-body')).to_contain_text('Marshall')
    expect(page.locator('#products-body')).not_to_contain_text('Kindle')
    checks.append('切回商品页保留原 DOM、筛选值和事件绑定，外壳不重建')
    tab('comments')
    expect(page.locator('#inbox-route')).to_be_enabled()
    page.locator('.listener-details summary').click()
    page.locator('#inbox-interval').fill('77')
    page.locator('#inbox-interval').dispatch_event('change')
    page.locator('#inbox-filter').select_option('attention')
    page.evaluate("window.commentInterval=document.querySelector('#inbox-interval')")
    page.evaluate('window.scrollTo(0, document.documentElement.scrollHeight)')
    old_scroll = page.evaluate('window.scrollY')
    tab('dm')
    expect(page.locator('#inbox-route')).to_be_enabled()
    page.locator('.listener-details summary').click()
    page.locator('#inbox-interval').fill('88')
    page.locator('#inbox-interval').dispatch_event('change')
    tab('comments')
    expect(page.locator('#inbox-interval')).to_have_value('77')
    expect(page.locator('#inbox-filter')).to_have_value('attention')
    expect(page.locator('#inbox-unsaved')).to_contain_text('未应用')
    assert page.evaluate("commentInterval===document.querySelector('#inbox-interval')")
    assert abs(page.evaluate('window.scrollY') - old_scroll) < 3
    assert not page.locator('#dialog').is_visible()
    before_polls = dict(polls)
    page.wait_for_timeout(5300)
    assert polls['dm'] == before_polls['dm'], 'Inactive inbox must not poll'
    assert polls['comment'] > before_polls['comment'], 'Restored inbox must resume polling'
    expect(page.locator('#inbox-interval')).to_have_value('77')
    tab('dm')
    expect(page.locator('#inbox-interval')).to_have_value('88')
    checks.append('私信和留言配置独立保留，恢复滚动位置，后台刷新不覆盖未保存配置')
    tab('publish')
    expect(page.locator('#draft-description')).to_be_visible()
    page.locator('#draft-description').fill('仅用于测试的未保存商品内容')
    page.locator('#draft-price').fill('123')
    tab('messages')
    expect(page.locator('[data-act="open-chat"]').first).to_be_visible()
    page.locator('[data-act="open-chat"]').first.click()
    expect(page.locator('#chat-text')).to_be_visible()
    selected_url = page.url
    page.locator('#chat-text').fill('尚未发送的消息，保留在这里')
    page.locator('#chat-scroll').evaluate("node=>{node.style.maxHeight='60px';node.style.flex='none';node.scrollTop=25;}")
    chat_scroll = page.locator('#chat-scroll').evaluate('node=>node.scrollTop')
    assert chat_scroll > 0
    tab('publish')
    expect(page.locator('#draft-description')).to_have_value('仅用于测试的未保存商品内容')
    expect(page.locator('#draft-price')).to_have_value('123')
    tab('messages')
    expect(page.locator('#chat-text')).to_have_value('尚未发送的消息，保留在这里')
    assert page.url == selected_url
    assert page.locator('#chat-scroll').evaluate('node=>node.scrollTop') == chat_scroll
    page.go_back()
    expect(page.locator('#draft-description')).to_have_value('仅用于测试的未保存商品内容')
    page.go_forward()
    expect(page.locator('#chat-text')).to_have_value('尚未发送的消息，保留在这里')
    checks.append('商品草稿、会话选择和未发消息在切页与浏览器前进后退后保留')
    page.locator('#active-account').select_option('demo-studio')
    expect(page.locator('#dialog')).to_be_visible()
    page.get_by_role('button', name='放弃修改并继续', exact=True).click()
    expect(page.locator('#active-account')).to_have_value('demo-studio')
    assert page.evaluate('!window.savedShell')
    tab('publish')
    expect(page.locator('#draft-description')).not_to_have_value('仅用于测试的未保存商品内容')
    checks.append('切账号保留确认机制，重新载入后不会带入旧账号的缓存与草稿')
    tab('products')
    expect(page.locator('#product-search')).to_be_visible()
    page.evaluate("window.beforeMutation=document.querySelector('#product-search')")
    tab('templates')
    expect(page.get_by_role('heading', name='话术库', exact=True)).to_be_visible()
    page.locator('[data-act="new-template"]').first.click()
    page.locator('#template-title').fill('缓存失效验证')
    page.locator('#template-text').fill('只保存演示空间本地话术，不发送消息。')
    page.locator('[data-act="save-template"]').click()
    expect(page.locator('.template-card').filter(has_text='缓存失效验证')).to_be_visible()
    tab('products')
    expect(page.locator('#product-search')).to_be_visible()
    assert page.evaluate("beforeMutation!==document.querySelector('#product-search')")
    checks.append('成功保存后无未保存内容的旧页面缓存失效，返回读取最新数据')
    tab('publish')
    expect(page.locator('#draft-description')).to_be_visible()
    page.locator('[data-act="new-draft"]').click()
    expect(page.locator('#draft-description')).to_have_value('')
    page.locator('#draft-description').fill('新草稿替换测试')
    page.locator('[data-act="new-draft"]').click()
    expect(page.locator('#dialog')).to_be_visible()
    page.get_by_role('button', name='放弃修改并继续', exact=True).click()
    expect(page.locator('#draft-description')).to_have_value('')
    checks.append('同一地址新建草稿仍重新初始化，不复用被放弃的内容')
    assert not errors, errors
    browser.close()
print({'checks': checks, 'page_errors': errors})
